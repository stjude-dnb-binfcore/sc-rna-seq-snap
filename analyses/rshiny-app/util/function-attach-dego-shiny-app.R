attach_volcano_reports_to_shiny_app <- function(shiny_dir,
                                               root_dir,
                                               dego_mode = "global_interaction") {
  resolved <- resolve_dego_shiny_plots_dir(root_dir, dego_mode)
  if (is.null(resolved)) {
    return(invisible(FALSE))
  }
  plots_dir <- resolved$dir
  dego_mode <- resolved$mode

  all_reports <- sort(list.files(
    plots_dir,
    pattern = "^Report-.*\\.html$",
    ignore.case = TRUE,
    full.names = FALSE
  ))
  volcano_files <- all_reports[grepl("volcano", all_reports, ignore.case = TRUE)]
  if (length(volcano_files) == 0L) {
    message("No Report-*volcano*.html in ", plots_dir, "; skipping Volcano Shiny tab")
    return(invisible(FALSE))
  }

  www_dir <- file.path(shiny_dir, "www", "volcano_reports")
  if (!dir.exists(www_dir)) {
    dir.create(www_dir, recursive = TRUE)
  }

  for (f in volcano_files) {
    file.copy(
      file.path(plots_dir, f),
      file.path(www_dir, f),
      overwrite = TRUE
    )
  }

  write_volcano_reports_index_html(volcano_files, www_dir, dego_mode)

  manifest <- data.frame(
    report = volcano_files,
    source_path = file.path(plots_dir, volcano_files),
    shiny_www_path = file.path("www/volcano_reports", volcano_files),
    dego_mode = dego_mode,
    stringsAsFactors = FALSE
  )
  manifest_path <- file.path(dirname(shiny_dir), "volcano_plots_shiny_manifest.tsv")
  utils::write.table(
    manifest,
    manifest_path,
    sep = "\t",
    row.names = FALSE,
    quote = FALSE
  )

  inject_volcano_tab_in_ui(file.path(shiny_dir, "ui.R"))
  message(
    "Attached ", length(volcano_files), " volcano HTML report(s) to Shiny app (mode=",
    dego_mode, "). Open Annotations → \"Volcano plots\" or www/volcano_reports/index.html"
  )
  invisible(TRUE)
}

#' @param shiny_dir path to results/shinyApp (contains ui.R)
#' @export
attach_de_go_reports_to_shiny_app <- function(shiny_dir,
                                             root_dir,
                                             dego_mode = "global_interaction",
                                             resolution_list = NULL) {
  resolved <- resolve_dego_shiny_plots_dir(root_dir, dego_mode)
  if (is.null(resolved)) {
    message(
      "include_de_go_analysis_rshiny_app_module is YES but de-go plots were not found ",
      "for mode=", dego_mode, ". Run de-go-analysis first."
    )
    return(invisible(FALSE))
  }
  plots_dir <- resolved$dir
  dego_mode <- resolved$mode

  report_files <- sort(list.files(
    plots_dir,
    pattern = "^Report-.*\\.html$",
    ignore.case = TRUE,
    full.names = FALSE
  ))
  if (length(report_files) == 0L) {
    message("No Report-*.html files in ", plots_dir)
    return(invisible(FALSE))
  }

  www_dir <- file.path(shiny_dir, "www", "de_go_reports")
  if (!dir.exists(www_dir)) {
    dir.create(www_dir, recursive = TRUE)
  }

  for (f in report_files) {
    file.copy(
      file.path(plots_dir, f),
      file.path(www_dir, f),
      overwrite = TRUE
    )
  }

  write_dego_reports_index_html(report_files, www_dir, dego_mode)

  manifest <- data.frame(
    report = report_files,
    source_path = file.path(plots_dir, report_files),
    shiny_www_path = file.path("www/de_go_reports", report_files),
    dego_mode = dego_mode,
    stringsAsFactors = FALSE
  )
  if (!is.null(resolution_list) && nzchar(as.character(resolution_list))) {
    manifest$resolution_list <- as.character(resolution_list)
  }
  manifest_path <- file.path(dirname(shiny_dir), "de_go_shiny_manifest.tsv")
  utils::write.table(
    manifest,
    manifest_path,
    sep = "\t",
    row.names = FALSE,
    quote = FALSE
  )

  inject_dego_tab_in_ui(file.path(shiny_dir, "ui.R"))
  message(
    "Attached ", length(report_files), " de-go HTML report(s) to Shiny app (mode=",
    dego_mode, "). Open tab \"DE & GO reports\" or www/de_go_reports/index.html"
  )

  attach_volcano_reports_to_shiny_app(
    shiny_dir = shiny_dir,
    root_dir = root_dir,
    dego_mode = dego_mode
  )
  invisible(TRUE)
}

